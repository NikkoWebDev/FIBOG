async function main() {
  const { data: existing, error: selError } = await supabase.from('grupos').select('nombre');
  if (selError) { console.error('ERROR select:', selError.message); process.exit(1); }
  const names = new Set((existing || []).map((g) => g.nombre));
  const missing = GRUPOS.filter((g) => !names.has(g.nombre));
  console.log(`Existentes: ${names.size}. Nuevos a insertar: ${missing.length}.`);
  if (!missing.length) return;
  const { data, error } = await supabase.from('grupos').insert(missing).select('nombre');
  if (error) { console.error('ERROR insert:', error.message); process.exit(1); }
  console.log(`OK: ${(data || []).length} grupos insertados.`);
}

