async function main() {
  console.log(`Seed de ${GRUPOS.length} grupos faltantes (inserta solo los ausentes por nombre)...`);
  const { data: existing, error: selError } = await supabase.from('grupos').select('nombre');
  if (selError) {
    console.error('ERROR select:', selError.message);
    process.exit(1);
  }
  const existingNames = new Set((existing || []).map((g) => g.nombre));
  const missing = GRUPOS.filter((g) => !existingNames.has(g.nombre));
  console.log(`Existentes: ${existingNames.size}. Nuevos a insertar: ${missing.length}.`);
  if (missing.length === 0) return;
  const { data, error } = await supabase.from('grupos').insert(missing).select('id,nombre');
  if (error) {
    console.error('ERROR insert:', error.message);
    process.exit(1);
  }
  console.log(`OK: ${(data || []).length} grupos insertados.`);
  for (const g of (data || [])) console.log(' -', g.nombre);
}

main();
